//! Build-time ABI contract enforcement.
//!
//! 1. Locates the musl source tree (`MUSL_SRC`, default /home/dicov/musl).
//! 2. Generates `bits/alltypes.h` / `bits/syscall.h` with musl's OWN
//!    tooling (tools/mkalltypes.sed), exactly like Makefile lines 98-103.
//! 3. Compiles probe/probe.c against the REAL musl headers with gcc
//!    (`-nostdinc -ffreestanding`, mirroring musl's CFLAGS_C99FSE),
//!    runs it, and emits OUT_DIR/abi_probed.rs.
//! 4. lib.rs static-asserts every constant against the Rust mirrors.
//!
//! Any failure here fails the build. There is intentionally no fallback.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

fn run(cmd: &mut Command, what: &str) -> String {
    let out = cmd
        .output()
        .unwrap_or_else(|e| panic!("zlibc build.rs: cannot run {what}: {e}"));
    if !out.status.success() {
        panic!(
            "zlibc build.rs: {what} failed:\n{}",
            String::from_utf8_lossy(&out.stderr)
        );
    }
    String::from_utf8(out.stdout).unwrap_or_else(|_| panic!("zlibc build.rs: {what} not UTF-8"))
}

fn main() {
    println!("cargo:rerun-if-changed=probe/probe.c");
    println!("cargo:rerun-if-changed=src/abi.rs");
    println!("cargo:rerun-if-env-changed=MUSL_SRC");

    let arch = env::var("CARGO_CFG_TARGET_ARCH").unwrap();
    if arch != "x86_64" {
        panic!("zlibc build.rs: only x86_64 is wired up (got {arch})");
    }

    let musl = PathBuf::from(env::var("MUSL_SRC").unwrap_or_else(|_| "/home/dicov/musl".into()));
    for p in [
        "include/stdio.h",
        "src/internal/stdio_impl.h",
        "tools/mkalltypes.sed",
    ] {
        assert!(
            musl.join(p).exists(),
            "zlibc build.rs: MUSL_SRC={musl:?} missing {p}"
        );
    }

    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    let gen = out.join("gen");
    let bits = gen.join("bits");
    fs::create_dir_all(&bits).unwrap();

    // bits/alltypes.h — same command as the musl Makefile, executed
    // with the real sed so the semantics stay musl's, not ours.
    let a_in = fs::read_to_string(musl.join("arch/x86_64/bits/alltypes.h.in")).unwrap();
    let g_in = fs::read_to_string(musl.join("include/alltypes.h.in")).unwrap();
    let combined = format!("{a_in}\n{g_in}");
    let tmp_in = out.join("alltypes.in");
    fs::write(&tmp_in, combined).unwrap();
    let sed_out = run(
        Command::new("sed")
            .arg("-f")
            .arg(musl.join("tools/mkalltypes.sed"))
            .arg(&tmp_in),
        "sed tools/mkalltypes.sed",
    );
    fs::write(bits.join("alltypes.h"), sed_out).unwrap();

    // bits/syscall.h — same two steps as the musl Makefile (cp + append).
    let sc_in = musl.join("arch/x86_64/bits/syscall.h.in");
    assert!(
        sc_in.exists(),
        "zlibc build.rs: missing arch/x86_64/bits/syscall.h.in"
    );
    let mut sc = fs::read_to_string(&sc_in).unwrap();
    for line in sc.clone().lines() {
        // sed -n -e s/__NR_/SYS_/p
        if let Some(rest) = line.strip_prefix("#define __NR_") {
            sc.push_str(&format!("#define SYS_{rest}\n"));
        }
    }
    fs::write(bits.join("syscall.h"), sc).unwrap();

    // Compile the probe like musl compiles itself: no host libc headers,
    // and -D_XOPEN_SOURCE=700 exactly as musl's CFLAGS_ALL — without it,
    // public headers withhold __NEED_off_t/__NEED_locale_t and the TU
    // breaks (this exact failure was observed in CI).
    let probe_bin = out.join("probe");
    let st = Command::new("gcc")
        .args(["-std=c99", "-D_XOPEN_SOURCE=700", "-ffreestanding", "-nostdinc", "-o"])
        .arg(&probe_bin)
        .arg("probe/probe.c")
        .arg(format!("-I{}", gen.display()))
        .arg(format!("-I{}", musl.join("arch/x86_64").display()))
        .arg(format!("-I{}", musl.join("arch/generic").display()))
        .arg(format!("-I{}", musl.join("src/include").display()))
        .arg(format!("-I{}", musl.join("src/internal").display()))
        .arg(format!("-I{}", musl.join("include").display()))
        .current_dir(Path::new(&env::var("CARGO_MANIFEST_DIR").unwrap()))
        .status()
        .unwrap_or_else(|e| panic!("zlibc build.rs: cannot run gcc (is it installed?): {e}"));
    assert!(
        st.success(),
        "zlibc build.rs: gcc failed to compile probe/probe.c"
    );

    let measured = run(&mut Command::new(&probe_bin), "probe binary");

    let mut rs = String::from("// @generated by build.rs from real musl headers — do not edit.\n");
    let mut n = 0;
    for line in measured.lines() {
        let (k, v) = line
            .split_once(' ')
            .unwrap_or_else(|| panic!("zlibc build.rs: bad probe line: {line:?}"));
        let _: u64 = v
            .parse()
            .unwrap_or_else(|_| panic!("zlibc build.rs: bad value: {line:?}"));
        rs.push_str(&format!("pub const PROBE_{k}: usize = {v};\n"));
        n += 1;
    }
    assert!(
        n >= 30,
        "zlibc build.rs: probe emitted only {n} values, expected 30+"
    );
    fs::write(out.join("abi_probed.rs"), rs).unwrap();
    println!("cargo:warning=zlibc ABI probe: {n} sizes/offsets measured from {musl:?}");
}
